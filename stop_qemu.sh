#!/bin/bash

# =======================================================
# QEMU 进程温和终止脚本
# 目的: 查找并终止 QEMU 进程，并在退出时重置终端设置。
# -------------------------------------------------------
# 注意：使用 'kill' (SIGTERM) 而非 'kill -9' (SIGKILL)，
# 允许 QEMU 在终止前恢复终端状态，防止显示错乱。
# =======================================================

# 查找所有包含 qemu- 的进程 (使用 [q]emu-* 避免 grep 进程本身)
PIDS=$(ps aux | grep '[q]emu-' | awk '{print $2}')

if [ -z "$PIDS" ]; then
    echo "未找到 qemu- 相关进程"
else
    echo "找到以下 qemu- 相关进程: $PIDS"
    
    # 使用 SIGTERM (默认信号) 允许进程进行清理
    echo "$PIDS" | xargs sudo kill
    
    # 增加一个短暂的延迟，确保 QEMU 有时间接收信号并清理
    sleep 1
    
    # 强制重置终端设置。这是解决终端错乱的关键步骤。
    stty sane
fi

echo "QEMU 终止脚本执行完毕。"
